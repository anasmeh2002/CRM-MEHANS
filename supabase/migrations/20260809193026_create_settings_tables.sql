/*
# Create settings, notifications, api_keys, and integrations tables

1. New Tables
- `settings` — single-row table storing organization profile, branding, and workspace config
  - id (int, primary key, always 1), org_name, website, industry, timezone, logo_path,
    primary_color, theme, updated_at
- `notifications` — real notifications generated by CRM events
  - id (uuid), title, description, type, record_type, record_id, read (bool), created_at
- `api_keys` — API keys for workspace access
  - id (uuid), name, key_hash (text, the SHA-256 hash), key_prefix (text, first 8 chars for display),
    created_at, revoked_at
- `integrations` — integration connection state
  - id (uuid), service (text, unique), connected (bool), config (jsonb), created_at, updated_at
- `role_permissions` — per-role CRUD permissions per module
  - id (uuid), role (text), module (text), can_view (bool), can_create (bool), can_edit (bool), can_delete (bool)

2. Security
- Enable RLS on all new tables.
- Allow anon + authenticated full CRUD (single-tenant, no auth).

3. Notes
- `settings` uses a fixed id of 1 so we always have exactly one row (upsert pattern).
- API keys store only the hash and a display prefix — never the raw key.
*/

CREATE TABLE IF NOT EXISTS settings (
  id int PRIMARY KEY DEFAULT 1,
  org_name text NOT NULL DEFAULT 'MEHANS Real Estate',
  website text,
  industry text DEFAULT 'Real Estate',
  timezone text DEFAULT 'America/New_York',
  logo_path text,
  primary_color text DEFAULT '#D4AF37',
  theme text DEFAULT 'dark',
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public all settings" ON settings;
CREATE POLICY "public all settings" ON settings FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- Seed the single row if it doesn't exist
INSERT INTO settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  description text,
  type text DEFAULT 'info',
  record_type text,
  record_id uuid,
  read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public all notifications" ON notifications;
CREATE POLICY "public all notifications" ON notifications FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE TABLE IF NOT EXISTS api_keys (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  key_hash text NOT NULL,
  key_prefix text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);

ALTER TABLE api_keys ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public all api_keys" ON api_keys;
CREATE POLICY "public all api_keys" ON api_keys FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE TABLE IF NOT EXISTS integrations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  service text UNIQUE NOT NULL,
  connected boolean NOT NULL DEFAULT false,
  config jsonb DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE integrations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public all integrations" ON integrations;
CREATE POLICY "public all integrations" ON integrations FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

